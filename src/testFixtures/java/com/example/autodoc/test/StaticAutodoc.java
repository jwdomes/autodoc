package com.example.autodoc.test;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.tngtech.archunit.core.domain.JavaClass;
import com.tngtech.archunit.core.domain.JavaClasses;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.stream.Collectors;

/**
 * Writes the static docs in each enabled {@link DocFormat}: the graph (flow.mmd, and flow.svg for
 * markdown-image) and an index page (README.md: graph, steps, scenarios).
 */
public final class StaticAutodoc {

    /** Subdirectory of the docs holding the markdown-image pages and their images. */
    static final String IMAGE_DIR = "markdown-image";

    public static void verify(AutodocSettings settings) throws IOException {
        verify(settings, DocWriter.fromSystemProperties());
    }

    public static void verify(AutodocSettings settings, DocWriter writer) throws IOException {
        JavaClasses classes = settings.importClasses();
        Map<String, String> labels = FlowParticipants.labels(classes);
        FlowGraph graph = new FlowGraph(classes, settings.basePackage(), labels);
        assertFalse(graph.nodes().isEmpty(), "No @FlowStep methods under " + settings.basePackage());

        Path docs = settings.docsDir();
        String mermaid = graph.mermaid();
        if (writer.writes(DocFormat.MERMAID)) {
            writer.write(docs.resolve("flow.mmd"), mermaid);
        }
        if (writer.writes(DocFormat.MARKDOWN)) {
            Path page = docs.resolve("README.md");
            writer.write(page, index(settings, graph, page, "```mermaid\n" + mermaid + "```", labels));
        }
        if (writer.writes(DocFormat.MARKDOWN_IMAGE)) {
            Path page = docs.resolve(IMAGE_DIR).resolve("README.md");
            writer.write(docs.resolve(IMAGE_DIR).resolve("flow.svg"), SvgGraph.render(graph));
            writer.write(page, index(settings, graph, page, "![Flow graph](flow.svg)", labels));
        }
        if (writer.verifying()) {
            verifyEveryScenarioHasAPage(settings, writer);
        }
    }

    private static String index(AutodocSettings settings, FlowGraph graph, Path page, String diagram,
                                Map<String, String> labels) throws IOException {
        StringBuilder sb = new StringBuilder("""
                # Flow docs

                Generated by the autodoc tests. Don't edit by hand: rerun the tests and commit the result.

                ## Flow

                """).append(diagram).append("""


                ## Steps

                | Step | Participant | Code |
                | --- | --- | --- |
                """);
        Path sources = page.toAbsolutePath().getParent().relativize(Path.of("src/main/java").toAbsolutePath());
        for (FlowGraph.Node n : graph.nodes()) {
            sb.append("| %s | %s | %s |\n".formatted(n.text(), labels.getOrDefault(n.participant(), n.participant()),
                    codeLink(sources, n)));
        }
        sb.append("""

                ## Scenarios

                | Scenario | Description | Request | Properties | Expected status |
                | --- | --- | --- | --- | --- |
                """);
        for (String name : Scenario.names(settings.scenariosDir()).toList()) {
            Scenario scenario = Scenario.load(settings.scenariosDir(), name);
            sb.append("| [%s](flows/%s.md) | %s | `%s %s` | %s | %d |\n".formatted(name, name,
                    scenario.description(), scenario.method(), scenario.path(), properties(scenario),
                    scenario.expectedStatus()));
        }
        return sb.toString();
    }

    private static String properties(Scenario scenario) {
        return scenario.properties().isEmpty() ? "default" : scenario.properties().entrySet().stream()
                .sorted(Map.Entry.comparingByKey())
                .map(e -> "`%s=%s`".formatted(e.getKey(), e.getValue()))
                .collect(Collectors.joining(", "));
    }

    /**
     * Each scenario test class runs only the scenarios for its properties, so a scenario whose properties no
     * class uses would silently never run, and its page would never exist. Checked in verify mode only: when
     * writing, test classes run in no fixed order, so pages may not exist yet.
     */
    private static void verifyEveryScenarioHasAPage(AutodocSettings settings, DocWriter writer) throws IOException {
        String page = writer.writes(DocFormat.MARKDOWN) ? "flows/%s.md"
                : writer.writes(DocFormat.MARKDOWN_IMAGE) ? IMAGE_DIR + "/flows/%s.md"
                : "flows/%s.mmd";
        List<String> missing = new ArrayList<>();
        for (String name : Scenario.names(settings.scenariosDir()).toList()) {
            if (!Files.exists(settings.docsDir().resolve(page.formatted(name)))) {
                missing.add(name + " " + Scenario.load(settings.scenariosDir(), name).properties());
            }
        }
        assertTrue(missing.isEmpty(), "Scenarios with no generated page (does a scenario test run their properties?): "
                + missing);
    }

    /** Class#method linking to the source file; no line numbers, so unrelated edits don't change the doc. */
    private static String codeLink(Path sources, FlowGraph.Node n) {
        JavaClass owner = n.method().getOwner();
        String file = "%s/%s/%s".formatted(sources.toString().replace('\\', '/'),
                owner.getPackageName().replace('.', '/'), owner.getSourceCodeLocation().getSourceFileName());
        return "[`%s#%s`](%s)".formatted(owner.getSimpleName(), n.method().getName(), file);
    }

    private StaticAutodoc() {
    }
}
